    // NOTE (BUGS.md P3-58 + H2): despite the old misleading name, this test
    // never compiled the generated source — `build_od_for_test` executes the
    // runtime EDS path instead. Semantic equivalence is checked here;
    // actual compilation of the emitted module is covered by
    // `generated_module_compiles_with_rustc` below.
    #[test]
    fn generated_fragments_match_runtime_resolution() {
        let eds = eds::parse(SAMPLE).unwrap();
        let source = generate_od_module(&eds, "build_od").unwrap();

        // Sanity-check emitted fragments before executing them.
        assert!(source.contains("pub fn build_od(node_id: u8)"));
        assert!(source.contains("node_id as i64 + (512)"));
        assert!(source.contains("DataType::Integer16"));

        // Compile+run the emitted function via a tiny dynamic harness.
        let od = build_od_for_test(&source);
        assert_eq!(
            od.read(canopen_core::types::Address::new(0x1000, 0))
                .unwrap(),
            Value::Uint(0x10192)
        );
        assert_eq!(
            od.read(canopen_core::types::Address::new(0x6000, 1))
                .unwrap(),
            Value::Int(0x210)
        );
    }

    /// Evaluates the generated source by interpreting the two entries we
    /// know how to check without a compiler dependency: re-parses the EDS
    /// and builds the dictionary through the runtime path with node_id=16.
    fn build_od_for_test(_source: &str) -> canopen_core::object_dictionary::ObjectDictionary {
        // A full eval harness would need `syn`/compilation; production users
        // wire the generated file into build.rs. Here we verify semantics
        // via the runtime builder (same resolution logic).
        eds::parse(SAMPLE)
            .unwrap()
            .to_object_dictionary(16)
            .unwrap()
    }

    /// Compiles `source` against the workspace's `canopen_core` rlib and
    /// returns the produced binary; `tag` names the temporary artifacts.
    fn compile_generated(source: &str, fn_name: &str, tag: &str) -> std::path::PathBuf {
        let dir =
            std::env::temp_dir().join(format!("canopen_codegen_{}_{tag}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let mod_path = dir.join("generated.rs");
        std::fs::write(&mod_path, source).unwrap();
        let main_path = dir.join("main.rs");
        std::fs::write(
            &main_path,
            format!("mod generated;\nfn main() {{ let _od = generated::{fn_name}(16); }}\n"),
        )
        .unwrap();

        // Locate the canopen_core rlib produced by this workspace build so
        // rustc can resolve the fully-qualified `canopen_core::*` paths.
        let manifest_dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
        let deps_dir = manifest_dir
            .parent()
            .expect("host is a workspace member")
            .join("target")
            .join("debug")
            .join("deps");
        let rlib = std::fs::read_dir(&deps_dir)
            .unwrap_or_else(|e| panic!("cannot read {deps_dir:?}: {e}"))
            .filter_map(Result::ok)
            .map(|e| e.path())
            .find(|p| {
                p.file_name()
                    .and_then(|n| n.to_str())
                    .is_some_and(|n| n.starts_with("libcanopen_core-") && n.ends_with(".rlib"))
            })
            .unwrap_or_else(|| panic!("libcanopen_core-*.rlib not found in {deps_dir:?}"));

        let bin = dir.join(format!("smoke_{tag}"));
        let out = std::process::Command::new("rustc")
            .arg("--edition=2021")
            .arg("--crate-name")
            .arg("codegen_smoke")
            .arg("--extern")
            .arg(format!("canopen_core={}", rlib.display()))
            .arg("-L")
            .arg(format!("dependency={}", deps_dir.display()))
            .arg("-o")
            .arg(&bin)
            .arg(&main_path)
            .output()
            .expect("rustc must be on PATH");
        assert!(
            out.status.success(),
            "generated module ({tag}) failed to compile:\n{}",
            String::from_utf8_lossy(&out.stderr)
        );
        bin
    }

    #[test]
    fn generated_module_compiles_with_rustc() {
        // BUGS.md H2: `generated_fragments_match_runtime_resolution` never
        // compiles the emitted module — a syntax/type error in the
        // generated source would go unnoticed. Actually compile it against
        // the workspace's canopen_core rlib and run the resulting binary so
        // `build_od(node_id)` is exercised for real.
        let eds = eds::parse(SAMPLE).unwrap();
        let source = generate_od_module(&eds, "build_od").unwrap();
        let bin = compile_generated(&source, "build_od", "sample");
        let run = std::process::Command::new(bin)
            .output()
            .expect("run compiled smoke binary");
        assert!(
            run.status.success(),
            "generated build_od(16) failed at runtime:\n{}",
            String::from_utf8_lossy(&run.stderr)
        );

        // 十H1: RICH carries a VisibleString default (owned `String`) and
        // must compile and run like SAMPLE.
        let rich = eds::parse(RICH).unwrap();
        let rich_source = generate_od_module(&rich, "build_rich").unwrap();
        let rich_bin = compile_generated(&rich_source, "build_rich", "rich");
        let run = std::process::Command::new(rich_bin)
            .output()
            .expect("run compiled rich binary");
        assert!(
            run.status.success(),
            "generated build_rich(16) failed at runtime:\n{}",
            String::from_utf8_lossy(&run.stderr)
        );

        // 十H2/十M14: panic-emitting defaults (invalid strings, short TIME,
        // non-numeric Boolean) must still produce compilable Rust — the
        // panic is the *intended* runtime behaviour on construction.
        let panics = eds::parse(PANIC_DEFAULTS).unwrap();
        let panic_source = generate_od_module(&panics, "build_panic").unwrap();
        let _ = compile_generated(&panic_source, "build_panic", "panic");
    }
